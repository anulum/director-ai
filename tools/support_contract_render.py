# Director-AI — render the production support contract as a Markdown table
"""Render the support contract as the one generated table the docs use.

The table states each operation's support, installation and activation in
separate columns, with the meaning sentence above it. The scope notes sit
beside their rows, so a production-qualified transport row is never read as
a production-qualified verdict. A second table lists each setting the
production profile turns on with the support of the operation that owns it,
so an experimental component that production enables is labelled as such.
"""

from __future__ import annotations

from director_ai.support_contract import Operation, SupportContract

GENERATED_PATH = "docs/_generated/production_support.md"
"""Where the rendered table is committed."""
GENERATED_PATHS = (GENERATED_PATH, "docs-site/deployment/production-support.md")
"""Every committed copy of the full table; the second serves the documentation site."""


def _covers(operation: Operation) -> str:
    """Return what an operation covers, as inline code."""
    parts: list[str] = []
    for command in operation.commands:
        if operation.subcommands:
            parts.extend(f"`{command} {sub}`" for sub in operation.subcommands)
        else:
            parts.append(f"`{command}`")
    parts.extend(f"`{name}`" for name in operation.exports)
    parts.extend(f"`{module}`" for module in operation.imports)
    parts.extend(f"`{route}`" for route in operation.routes)
    return ", ".join(parts)


def _installation(operation: Operation) -> str:
    """Return an operation's installation cell, with its prerequisites."""
    if operation.installation is None:
        return "not claimed"
    extras = "".join(f" + `{extra}`" for extra in operation.prerequisites)
    return f"{operation.installation}{extras}"


def render_table(contract: SupportContract) -> str:
    """Return the contract as Markdown.

    Parameters
    ----------
    contract : SupportContract
        A contract that passed :func:`director_ai.support_contract.contract_refusals`.

    Returns
    -------
    str
        The generated page, ending in a newline.
    """
    owners = {operation.identifier: operation for operation in contract.operations}
    lines = [
        "<!-- Generated by tools/support_contract_check.py --write; do not edit. -->",
        "",
        "# Production support contract",
        "",
        contract.meaning,
        "",
        "| Operation | Support | Installation | Activation | Covers | Scope |",
        "|---|---|---|---|---|---|",
    ]
    for operation in contract.operations:
        lines.append(
            f"| {operation.title} (`{operation.identifier}`) | {operation.support} "
            f"| {_installation(operation)} | {operation.activation} "
            f"| {_covers(operation)} | {operation.note} |"
        )
    lines += [
        "",
        "## Settings the production profile turns on",
        "",
        "| Setting | Owning operation | Its support |",
        "|---|---|---|",
    ]
    for default in contract.production_defaults:
        owner = owners[default.owner]
        lines.append(
            f"| `{default.setting}` | `{owner.identifier}` | {owner.support} |"
        )
    namespaces = ", ".join(f"`{name}`" for name in contract.experimental_namespaces)
    lines += [
        "",
        "## Everything else is experimental",
        "",
        f"{len(contract.experimental_exports)} further public exports and "
        f"{len(contract.experimental_commands)} further CLI commands are "
        "experimental, as is every subcommand, route or module not named above. "
        f"So are these namespaces: {namespaces}.",
        "",
    ]
    return "\n".join(lines)


BLOCK_START = "<!-- production-support:start -->"
BLOCK_END = "<!-- production-support:end -->"
DOC_BLOCKS = (
    ("README.md", "docs/_generated/production_support.md"),
    ("docs/PRODUCTION_CHECKLIST.md", "_generated/production_support.md"),
    ("docs-site/deployment/production.md", "production-support.md"),
)
"""Each public page that carries the generated block, and its relative link to the full table."""


def render_block(contract: SupportContract, link: str) -> str:
    """Return the compact block the public pages carry, markers included.

    Parameters
    ----------
    contract : SupportContract
        A contract that passed the checks.
    link : str
        Where the page links to the full generated table.

    Returns
    -------
    str
        The block, from its start marker to its end marker, with no newline
        after the end marker.
    """
    qualified = [
        op for op in contract.operations if op.support == "production-qualified"
    ]
    lines = [
        BLOCK_START,
        "<!-- Generated by tools/support_contract_check.py --write; do not edit. -->",
        "",
        contract.meaning,
        "",
    ]
    if qualified:
        lines += [
            "| Production-qualified operation | Installation | Activation | Scope |",
            "|---|---|---|---|",
        ]
        lines.extend(
            f"| {op.title} | {_installation(op)} | {op.activation} | {op.note} |"
            for op in qualified
        )
    else:
        lines.append("No operation is production-qualified yet.")
    owners = {op.identifier: op for op in contract.operations}
    enabled = sorted(
        {
            owners[default.owner].title
            for default in contract.production_defaults
            if owners[default.owner].support == "experimental"
        }
    )
    lines += [
        "",
        "Every other export, command, subcommand and route is experimental: "
        "source-available for evaluation, and its API may change. The production "
        "profile also turns on these experimental components: "
        + "; ".join(enabled)
        + ".",
        "",
        f"The full table: [production support contract]({link}).",
        BLOCK_END,
    ]
    return "\n".join(lines)
